import type { CatalogCategory, ComponentCatalogItem } from "./types";

/**
 * Danh mục component.
 *
 * `primitive` = tầng shadcn trong `src/components/ui/` — giữ nguyên, không di
 * chuyển file. `app` = component cấp app tự build. Hai hàm dựng bên dưới chỉ
 * để file này đọc được ở dạng bảng; chúng trả về object thuần.
 */

function primitive(
  slug: string,
  name: string,
  categories: CatalogCategory[],
  vi: string,
  en: string,
  options: Partial<ComponentCatalogItem> = {},
): ComponentCatalogItem {
  return {
    kind: "component",
    layer: "primitive",
    slug,
    name,
    categories,
    description: { vi, en },
    visibility: "public",
    ...options,
  };
}

function app(
  slug: string,
  name: string,
  categories: CatalogCategory[],
  vi: string,
  en: string,
  options: Partial<ComponentCatalogItem> = {},
): ComponentCatalogItem {
  return {
    kind: "component",
    layer: "app",
    slug,
    name,
    categories,
    description: { vi, en },
    visibility: "public",
    ...options,
  };
}

